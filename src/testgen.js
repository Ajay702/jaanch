// Writes a Playwright test per bug that replays the steps that triggered it and asserts the
// bug is gone. The tests fail today (proving the bug) and pass once it is fixed.
import { shortUrl } from './collector.js';

const q = (s) => JSON.stringify(s);

/** Turns recorded steps into Playwright statements. Steps without a stable locator are skipped. */
export function stepLines(steps, origin) {
  const lines = [];
  for (const s of steps) {
    if (s.error) continue;
    if (s.type === 'goto') {
      lines.push(`await page.goto(BASE_URL + ${q(pathOf(s.url, origin))});`);
    } else if (s.locator && s.type === 'fill') {
      lines.push(`await ${s.locator}.fill(${q(s.value ?? '')});`);
    } else if (s.locator && s.type === 'select') {
      lines.push(`await ${s.locator}.selectOption({ index: 1 });`);
    } else if (s.locator && s.type === 'click') {
      lines.push(`await ${s.locator}.click();`);
      lines.push(`await page.waitForLoadState('networkidle').catch(() => {});`);
    }
  }
  return lines;
}

const norm = (u) => {
  try {
    const x = new URL(u);
    return x.origin + x.pathname + x.search;
  } catch {
    return u;
  }
};

/** The unbroken run of non-navigation steps on the bug's page that ends with the triggering step. */
export function onPageRun(steps, issue) {
  const run = [];
  const page = norm(issue.pageUrl);
  for (let i = steps.findIndex((s) => s.n === issue.step); i >= 0; i--) {
    const s = steps[i];
    if (s.type === 'goto' || norm(s.fromUrl) !== page) break;
    run.unshift(s);
  }
  return run;
}

function pathOf(url, origin) {
  try {
    const u = new URL(url);
    return u.origin === origin ? u.pathname + u.search : url;
  } catch {
    return url;
  }
}

function assertionFor(issue, origin) {
  switch (issue.kind) {
    case 'js-exception':
    case 'console-error':
      return [`await page.waitForTimeout(500);`, `expect(errors, 'page should have no JavaScript errors').toEqual([]);`];
    case 'broken-page': {
      const target = pathOf(issue.url, origin);
      if (!issue.linkedFrom) {
        return [`const res = await page.goto(BASE_URL + ${q(target)});`, `expect(res.status(), ${q(`${target} should load`)}).toBeLessThan(400);`];
      }
      // Fixed either by creating the page or by removing the link to it.
      return [
        `await page.goto(BASE_URL + ${q(pathOf(issue.linkedFrom, origin))});`,
        `const linked = await page.$$eval('a[href]', (as, p) => as.some((a) => new URL(a.href).pathname === p), ${q(new URL(issue.url).pathname)});`,
        `if (linked) {`,
        `  const res = await page.request.get(BASE_URL + ${q(target)});`,
        `  expect(res.status(), ${q(`a link points to ${target}, so it should load`)}).toBeLessThan(400);`,
        `}`,
      ];
    }
    case 'http-error':
    case 'broken-image':
    case 'request-failed':
      return [
        `await page.waitForTimeout(500);`,
        `const bad = failed.filter((f) => f.url.includes(${q(shortUrl(issue.url).split('?')[0])}));`,
        `expect(bad, ${q(`${shortUrl(issue.url)} should succeed`)}).toEqual([]);`,
      ];
    default:
      return null;
  }
}

export function generateTests({ issues, steps, startUrl }) {
  const origin = new URL(startUrl).origin;
  const blocks = [];
  for (const issue of issues) {
    const assertion = assertionFor(issue, origin);
    if (!assertion) continue;
    // broken-page tests navigate directly; others open the page and replay the actions on it.
    const replay = issue.kind === 'broken-page' ? [] : [`await page.goto(BASE_URL + ${q(pathOf(issue.pageUrl || startUrl, origin))});`, ...(issue.onLoad ? [] : stepLines(onPageRun(steps, issue), origin))];
    const body = [...replay, ...assertion].map((l) => `  ${l}`).join('\n');
    blocks.push(`// ${issue.id} [${issue.severity}] ${issue.message.replace(/\n/g, ' ').slice(0, 140)}
test(${q(`${issue.id}: ${issue.title}`)}, async ({ page }) => {
${body}
});`);
  }
  if (!blocks.length) return null;
  return `// Generated by Jaanch (https://github.com/Ajay702/jaanch) on ${new Date().toISOString().slice(0, 10)}.
// Each test reproduces one bug Jaanch found. It FAILS while the bug exists and PASSES once fixed.
// Run: npx playwright test ${'<this file>'}   (set BASE_URL to point at another environment)
import { test, expect } from '@playwright/test';

const BASE_URL = process.env.BASE_URL ?? ${q(origin)};

let errors = [];
let failed = [];
test.beforeEach(async ({ page }) => {
  errors = [];
  failed = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => {
    if (m.type() === 'error' && !m.text().startsWith('Failed to load resource')) errors.push(m.text());
  });
  page.on('response', (r) => {
    if (r.status() >= 400) failed.push({ url: r.url(), status: r.status() });
  });
  page.on('requestfailed', (r) => failed.push({ url: r.url(), status: 0 }));
});

${blocks.join('\n\n')}
`;
}
